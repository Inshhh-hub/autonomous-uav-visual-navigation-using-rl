function percept = oraclePerception(sectorDist, ecfg)
%ORACLEPERCEPTION  Perception output built from ground-truth sector distances.
%   Used for data collection, for the reactive baseline and as an
%   upper-bound ablation ("perfect perception").
dist = double(sectorDist(:));
occ = double(dist < ecfg.sectors.occupancyThreshold);
percept = struct( ...
    "sectorDist", dist, ...
    "occupancy", occ, ...
    "risk", 0, ...
    "features", single([dist / ecfg.camera.maxDepth; occ; 0]));
end
